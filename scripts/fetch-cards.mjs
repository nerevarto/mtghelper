// Build-time Scryfall fetch. Writes src/data/sets/<code>.js and regenerates index.js.
//
//   npm run fetch-cards          every code in SETS
//   npm run fetch-cards -- tla   overrides SETS
//
// Zero dependencies, Node 18+ (global fetch).

import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const SETS = ['hob']

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const OUT_DIR = join(ROOT, 'src', 'data', 'sets')
const MANIFEST = join(OUT_DIR, 'index.js')

const HEADERS = {
  'User-Agent': 'mtghelper/1.0',
  Accept: 'application/json',
}

const sleep = ms => new Promise(r => setTimeout(r, ms))

function fail(message) {
  console.error(`\n  ERROR  ${message}\n`)
  process.exit(1)
}

// Retries once on 429/503, honouring Retry-After. Anything else non-2xx is fatal.
async function getJson(url, { retried = false } = {}) {
  let res
  try {
    res = await fetch(url, { headers: HEADERS })
  } catch (err) {
    fail(`Network failure for ${url}: ${err.message}`)
  }

  if ((res.status === 429 || res.status === 503) && !retried) {
    const after = Number(res.headers.get('retry-after'))
    const waitMs = Number.isFinite(after) && after > 0 ? after * 1000 : 2000
    console.log(`  ${res.status} from Scryfall, retrying in ${waitMs}ms`)
    await sleep(waitMs)
    return getJson(url, { retried: true })
  }

  if (!res.ok) {
    fail(`${res.status} ${res.statusText} for ${url}`)
  }

  try {
    return await res.json()
  } catch (err) {
    fail(`Malformed JSON from ${url}: ${err.message}`)
  }
}

const faces = card => (Array.isArray(card.card_faces) && card.card_faces.length > 0 ? card.card_faces : [card])

// A card is dropped if EVERY face is a land, or EVERY face lacks a mana cost.
// Face-aware so a spell-front // land-back MDFC survives.
function dropReason(card) {
  const fs = faces(card)
  if (fs.every(f => (f.type_line || card.type_line || '').includes('Land'))) return 'land'
  if (fs.every(f => !f.mana_cost)) return 'no mana cost'
  return null
}

function pickImage(card, size) {
  return card.image_uris?.[size] ?? card.card_faces?.[0]?.image_uris?.[size] ?? null
}

function trim(card) {
  const out = {
    id: card.id,
    name: card.name,
    manaCost: card.mana_cost ?? '',
    cmc: card.cmc,
    typeLine: card.type_line ?? '',
    oracleText: card.oracle_text ?? '',
  }
  if (card.power !== undefined) out.power = card.power
  if (card.toughness !== undefined) out.toughness = card.toughness
  out.colors = card.colors ?? []
  out.rarity = card.rarity
  out.number = card.collector_number
  out.img = pickImage(card, 'normal')
  out.imgSmall = pickImage(card, 'small')
  if (Array.isArray(card.card_faces) && card.card_faces.length > 0) {
    out.faces = card.card_faces.map(f => ({
      name: f.name,
      manaCost: f.mana_cost ?? '',
      typeLine: f.type_line ?? '',
      oracleText: f.oracle_text ?? '',
    }))
  }
  return out
}

async function fetchSet(code) {
  console.log(`\n${code.toUpperCase()}`)

  const set = await getJson(`https://api.scryfall.com/sets/${encodeURIComponent(code)}`)
  console.log(`  ${set.name} (released ${set.released_at})`)

  // Buffer every page before writing — never leave a partial set file behind.
  const raw = []
  let url = `https://api.scryfall.com/cards/search?q=${encodeURIComponent(`set:${code}`)}&unique=cards&order=set`
  let page = 0
  while (url) {
    page++
    const body = await getJson(url)
    if (!Array.isArray(body.data) || body.data.length === 0) {
      fail(`Page ${page} of ${code} returned no card data`)
    }
    raw.push(...body.data)
    url = body.has_more ? body.next_page : null
    if (url) await sleep(100)
  }
  console.log(`  ${raw.length} cards over ${page} page${page === 1 ? '' : 's'}`)

  const cards = []
  const dropped = []
  for (const card of raw) {
    const reason = dropReason(card)
    if (reason) {
      dropped.push({ name: card.name, reason })
      continue
    }
    cards.push(trim(card))
  }

  for (const d of dropped) console.log(`  drop  ${d.name} — ${d.reason}`)
  console.log(`  ${dropped.length} dropped, ${cards.length} kept`)

  const file = join(OUT_DIR, `${code}.js`)
  const body = cards.map(c => `  ${JSON.stringify(c)},`).join('\n')
  await writeFile(file, `// Generated by scripts/fetch-cards.mjs — do not edit.\nexport const CARDS = [\n${body}\n]\n`, 'utf8')
  console.log(`  wrote src/data/sets/${code}.js`)

  return { code, name: set.name, released: set.released_at, count: cards.length }
}

// Merge: entries for sets not in this run are preserved, this run's entries overwrite.
async function readExistingManifest() {
  try {
    const text = await readFile(MANIFEST, 'utf8')
    const json = text.slice(text.indexOf('['), text.lastIndexOf(']') + 1)
    return JSON.parse(json.replace(/(\w+):/g, '"$1":').replace(/'/g, '"').replace(/,(\s*[\]}])/g, '$1'))
  } catch {
    return []
  }
}

async function writeManifest(entries) {
  const existing = await readExistingManifest()
  const byCode = new Map(existing.map(e => [e.code, e]))
  for (const e of entries) byCode.set(e.code, e)
  const merged = [...byCode.values()].sort((a, b) => b.released.localeCompare(a.released))

  const body = merged
    .map(e => `  { code: '${e.code}', name: ${JSON.stringify(e.name)}, released: '${e.released}', count: ${e.count} },`)
    .join('\n')
  await writeFile(
    MANIFEST,
    `// Generated by scripts/fetch-cards.mjs — do not edit.\nexport const SET_MANIFEST = [\n${body}\n]\n`,
    'utf8',
  )
  console.log(`\nmanifest: ${merged.map(e => `${e.code} (${e.count})`).join(', ')}`)
}

const codes = process.argv.slice(2).length > 0 ? process.argv.slice(2) : SETS

await mkdir(OUT_DIR, { recursive: true })
const entries = []
for (const code of codes) {
  entries.push(await fetchSet(code.toLowerCase()))
  await sleep(100)
}
await writeManifest(entries)
